"""BCR Algorithm 1 on the A.1 problem.

Backward induction over the K decision blocks: block K-1 trains first; when
block k trains, blocks k+1..K-1 are frozen at their trained values and the
state at t_k is generated by rolling the *reference control* (myopic quotes,
eta = 0, hard fills) from the randomised start Vpi0 ~ U[-Vbar/2, Vbar/2] —
BCR's frozen-downstream-measure construction. The known bias of this scheme
(per-block optimality against reference-induced state marginals, not global
optimality) is precisely what the exact-HJB comparison measures.

Fills: straight-through by default (forward = hard Bernoulli, backward =
gradient of the compensated probability) — the primary path per the
milestone-3 tau study; tau > 0 switches to the sigmoid relaxation (ablation).
The compensated reward is itself smooth in delta; fills only steer the state.

Per-neuron noisy GD (mean-field Langevin) with the BCR regulariser
Gamma(theta_i) = ||theta_i||^p + 1e-9 exp(||theta_i||):

    theta_i <- theta_i - lr * ( r * grad_i mean(-R) + Gamma'(theta_i)/(2 beta^2) )
               + (sigma / beta) sqrt(lr) xi_i,

with defaults beta = 100, sigma = sqrt(0.1) beta, geometric lr decay.
`regularised=False` is the unregularised arm (Gamma off, sigma = 0).

ERM discipline: the n training environments are fixed by the data key —
per-step noise is fold_in(data_key, m), so sample j is row j of every draw
and the same Z_j drives both the roll-in and the trained segment; nothing is
stored. Fresh-sample evaluation uses a disjoint key.
"""
from __future__ import annotations

from functools import partial
from typing import NamedTuple

import jax
import jax.numpy as jnp

from .config import ProblemSpec
from .hjb import make_ops
from .model import H, a_P, carry, intensity, myopic_quotes, penalty_hedge
from .nets import BlockNet, ControlMaps, control_maps, controls, init_stack

_V0_TAG = 4_000_000_000   # fold_in tag (uint32) reserved for the Vpi0 draw


class TrainConfig(NamedTuple):
    r: int = 64
    n: int = 32
    epochs: int = 1000
    lr0: float = 0.3
    lr1: float = 1e-3
    beta: float = 100.0
    sigma: float | None = None       # update noise = sigma*sqrt(lr)*xi;
                                     # None -> sqrt(2)/beta (canonical MFLD at
                                     # temperature 1/beta^2 for the normalised
                                     # loss). The Overlearning repo's setting
                                     # corresponds to sigma = sqrt(0.1).
    reg_p: float = 4.0
    regularised: bool = True
    tau: float = 0.0                 # 0 -> straight-through
    seed: int = 0


class TrainedPolicy(NamedTuple):
    stack: BlockNet                  # (K, r, ...) trained block nets
    cm: ControlMaps
    history: jnp.ndarray             # (K, epochs) per-block ERM objective


# ----------------------------------------------------------------------------
# Environment core (semantics matched to simulate.py / the evaluator)
# ----------------------------------------------------------------------------

def _env_consts(spec: ProblemSpec):
    ops = make_ops(spec)
    sides = jnp.asarray([1.0, -1.0])
    szV = spec.book.zV[:, None] * sides[None, :]
    return ops, szV


def _step_state(spec, ops, szV, nu, Vpi, delta, eta, U, dW, tau):
    """One environment step at batched states; returns (reward, nu', Vpi')."""
    m_, r, book = spec.market, spec.risk, spec.book
    dt = spec.time_grid.dt
    gate = (jnp.abs(Vpi[:, None, None] + szV[None])
            <= r.Vbar * (1.0 + 1e-12)).astype(jnp.float64)
    lam = intensity(ops.book2, delta)
    q = gate * lam * dt
    if tau == 0.0:
        hard = gate * (U < lam * dt)
        fill = jax.lax.stop_gradient(hard - q) + q        # straight-through
    else:
        fill = gate * jax.nn.sigmoid((lam * dt - U) / tau)
    revenue = dt * (gate * book.z[None, :, None] * delta * lam).sum((1, 2))
    reward = revenue + dt * (carry(m_, nu, Vpi)
                             - penalty_hedge(m_, r, Vpi, eta))
    Vpi = Vpi + (fill * szV[None]).sum((1, 2))
    nu = nu + a_P(m_, nu) * dt \
        + m_.xi * jnp.sqrt(jnp.maximum(nu, 1e-12)) * dW
    return reward, nu, Vpi


def _step_noise(data_key, m, n, N):
    k = jax.random.fold_in(data_key, m)
    kn, ku = jax.random.split(k)
    dW = jnp.sqrt(1.0) * jax.random.normal(kn, (n,))     # scaled by sqrt(dt) later
    U = jax.random.uniform(ku, (n, N, 2))
    return dW, U


def rollin_states(spec: ProblemSpec, data_key, n: int, upto: int):
    """Reference-control roll-in (myopic quotes, hard fills) to step `upto`."""
    ops, szV = _env_consts(spec)
    m_, r = spec.market, spec.risk
    dt = spec.time_grid.dt
    d_ref = jnp.broadcast_to(myopic_quotes(spec.book)[None, :, None],
                             (n, spec.book.zV.size, 2))
    Vpi0 = jax.random.uniform(jax.random.fold_in(data_key, _V0_TAG), (n,),
                              minval=-0.5 * r.Vbar, maxval=0.5 * r.Vbar)
    nu0 = jnp.full((n,), m_.nu0)

    def step(state, m):
        nu, Vpi = state
        dW, U = _step_noise(data_key, m, n, spec.book.zV.size)
        gate = (jnp.abs(Vpi[:, None, None] + szV[None])
                <= r.Vbar * (1.0 + 1e-12)).astype(jnp.float64)
        lam = intensity(ops.book2, d_ref)
        fill = gate * (U < lam * dt)
        Vpi = Vpi + (fill * szV[None]).sum((1, 2))
        nu = nu + a_P(m_, nu) * dt \
            + m_.xi * jnp.sqrt(jnp.maximum(nu, 1e-12)) * jnp.sqrt(dt) * dW
        return (nu, Vpi), None

    (nu, Vpi), _ = jax.lax.scan(step, (nu0, Vpi0), jnp.arange(upto))
    return nu, Vpi


def rollout_value(theta_k, k: int, stack: BlockNet, cm: ControlMaps,
                  spec: ProblemSpec, starts, data_key, tau: float, env=None):
    """Mean compensated objective over [t_{k s}, T] with block k's net
    theta_k (trainable) and downstream blocks from `stack` (frozen).
    env = (ops, szV): pass precomputed constants when calling under jit."""
    ops, szV = _env_consts(spec) if env is None else env
    s = spec.time_grid.substeps_per_block
    dt = spec.time_grid.dt
    M = spec.time_grid.M
    params = jax.tree_util.tree_map(
        lambda f, t: f.at[k].set(t), stack, theta_k)
    nu0, Vpi0 = starts
    n = nu0.shape[0]

    def step(state, m):
        nu, Vpi, obj = state
        blk = m // s
        net = jax.tree_util.tree_map(lambda f: f[blk], params)
        delta, eta = controls(net, cm, nu, Vpi)
        dW, U = _step_noise(data_key, m, n, spec.book.zV.size)
        reward, nu, Vpi = _step_state(spec, ops, szV, nu, Vpi, delta, eta,
                                      U, jnp.sqrt(dt) * dW, tau)
        return (nu, Vpi, obj + reward), None

    (nu, Vpi, obj), _ = jax.lax.scan(
        step, (nu0, Vpi0, jnp.zeros(n)), jnp.arange(k * s, M))
    return obj.mean()


# ----------------------------------------------------------------------------
# Per-neuron noisy GD
# ----------------------------------------------------------------------------

def _neuron_norms(theta: BlockNet):
    return jnp.sqrt((theta.a ** 2).sum(-1) + theta.b ** 2
                    + (theta.c ** 2).sum(-1))            # (r,)


def _reg_coef(theta: BlockNet, p: float):
    nrm = jnp.maximum(_neuron_norms(theta), 1e-12)
    return p * nrm ** (p - 2.0) + 1e-9 * jnp.exp(jnp.minimum(nrm, 40.0)) / nrm


def objective_scale(spec: ProblemSpec) -> float:
    """Myopic revenue supersolution bound: T * sum_{i,s} z^i H^i(0). The loss
    is normalised by this so lr / beta / Gamma live at O(1) scales."""
    return float(spec.time_grid.T
                 * 2.0 * (spec.book.z * H(spec.book, 0.0)).sum())


def train_block(k: int, stack: BlockNet, spec: ProblemSpec, cm: ControlMaps,
                cfg: TrainConfig, data_key, noise_key):
    starts = rollin_states(spec, data_key, cfg.n,
                           k * spec.time_grid.substeps_per_block)
    env = _env_consts(spec)
    scale = objective_scale(spec)
    sigma = (jnp.sqrt(2.0) / cfg.beta) if cfg.sigma is None else cfg.sigma
    sigma = sigma if cfg.regularised else 0.0
    lrs = cfg.lr0 * (cfg.lr1 / cfg.lr0) ** (jnp.arange(cfg.epochs)
                                            / max(cfg.epochs - 1, 1))
    loss = lambda th: -rollout_value(th, k, stack, cm, spec, starts,
                                     data_key, cfg.tau, env=env) / scale
    vgrad = jax.value_and_grad(loss)

    def epoch(carry_, xs):
        theta, key = carry_
        lr, e = xs
        val, g = vgrad(theta)
        coef = _reg_coef(theta, cfg.reg_p) / (2.0 * cfg.beta ** 2) \
            if cfg.regularised else 0.0
        key, sub = jax.random.split(key)
        leaves, treedef = jax.tree_util.tree_flatten(theta)
        gl = jax.tree_util.tree_leaves(g)
        new = []
        for i, (t, gi) in enumerate(zip(leaves, gl)):
            c = coef[:, None] if (cfg.regularised and t.ndim == 2) else coef
            drift = cfg.r * gi + c * t
            xi = jax.random.normal(jax.random.fold_in(sub, i), t.shape)
            new.append(t - lr * drift + sigma * jnp.sqrt(lr) * xi)
        return (jax.tree_util.tree_unflatten(treedef, new), key), -val * scale

    theta0 = jax.tree_util.tree_map(lambda f: f[k], stack)
    (theta, _), hist = jax.jit(
        lambda t0, kk: jax.lax.scan(epoch, (t0, kk),
                                    (lrs, jnp.arange(cfg.epochs))))(
        theta0, noise_key)
    return jax.tree_util.tree_map(lambda f, t: f.at[k].set(t), stack, theta), hist


def train(spec: ProblemSpec, cfg: TrainConfig) -> TrainedPolicy:
    cm = control_maps(spec)
    base = jax.random.PRNGKey(cfg.seed)
    data_key = jax.random.fold_in(base, 1)
    stack = init_stack(jax.random.fold_in(base, 2), spec.time_grid.K_blocks,
                       cfg.r)
    hists = []
    for k in reversed(range(spec.time_grid.K_blocks)):
        stack, h = train_block(k, stack, spec, cm, cfg, data_key,
                               jax.random.fold_in(base, 100 + k))
        hists.append(h)
    return TrainedPolicy(stack=stack, cm=cm,
                         history=jnp.stack(hists[::-1]))


def full_objective(stack: BlockNet, cm: ControlMaps, spec: ProblemSpec,
                   data_key, n: int, tau: float = 0.0):
    """Full-horizon hard-fill objective under the trained stack, from the
    randomised Vpi0 of `data_key` — J_train with the training key, J_fresh
    with a disjoint one."""
    r = spec.risk
    Vpi0 = jax.random.uniform(jax.random.fold_in(data_key, _V0_TAG), (n,),
                              minval=-0.5 * r.Vbar, maxval=0.5 * r.Vbar)
    nu0 = jnp.full((n,), spec.market.nu0)
    return rollout_value(jax.tree_util.tree_map(lambda f: f[0], stack), 0,
                         stack, cm, spec, (nu0, Vpi0), data_key, tau)
